export const getPost = (slug: string) => posts.find((p) => p.slug === slug);

export const relatedPosts = (slug: string, count = 3) => {
  const current = getPost(slug);
  if (!current) return posts.slice(0, count);
  const same = posts.filter((p) => p.slug !== slug && p.category === current.category);
  const rest = posts.filter((p) => p.slug !== slug && p.category !== current.category);
  return [...same, ...rest].slice(0, count);
};

export const formatDate = (iso: string) => {
  try {
    return new Intl.DateTimeFormat('fa-IR', { year: 'numeric', month: 'long', day: 'numeric', calendar: 'persian' }).format(new Date(iso));
  } catch {
    return iso;
  }
};
